export const isReservedSlug = (slug: string): boolean => {
  if (!slug) return false;
  const cleanSlug = slug.trim().toLowerCase().replace(/[^a-z0-9-]/g, '');
  return RESERVED_SLUGS.includes(cleanSlug);
};
